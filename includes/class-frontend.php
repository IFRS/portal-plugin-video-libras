<?php
/**
 * Front-end floating video player.
 *
 * @package PortalVideoLibras
 */

namespace PortalVideoLibras;

/**
 * Renders the LIBRAS video player on singular content.
 */
final class Frontend {

	/**
	 * Hooks front-end assets and output.
	 *
	 * @return void
	 */
	public function register_hooks() {
		add_action( 'wp_enqueue_scripts', array( $this, 'enqueue_assets' ) );
		add_action( 'wp_footer', array( $this, 'render_player' ), 20 );
	}

	/**
	 * Enqueues assets only when a valid video is available.
	 *
	 * @return void
	 */
	public function enqueue_assets() {
		if ( ! $this->get_video_url() ) {
			return;
		}

		wp_enqueue_style(
			'portal-video-libras',
			PORTAL_VIDEO_LIBRAS_URL . 'assets/css/frontend.css',
			array(),
			PORTAL_VIDEO_LIBRAS_VERSION
		);

		wp_enqueue_script(
			'portal-video-libras',
			PORTAL_VIDEO_LIBRAS_URL . 'assets/js/frontend.js',
			array(),
			PORTAL_VIDEO_LIBRAS_VERSION,
			true
		);
	}

	/**
	 * Renders the widget in the footer.
	 *
	 * @return void
	 */
	public function render_player() {
		$url = $this->get_video_url();

		if ( ! $url ) {
			return;
		}

		$video = $this->get_video_markup( $url );

		if ( ! $video ) {
			return;
		}
		?>
		<div class="portal-libras-player">
			<button
				class="portal-libras-player__toggle"
				type="button"
				aria-label="<?php esc_attr_e( 'Abrir vídeo em LIBRAS', 'portal-video-libras' ); ?>"
				aria-expanded="false"
				aria-controls="portal-libras-player-panel"
			>
				<img src="<?php echo esc_url( PORTAL_VIDEO_LIBRAS_URL . 'assets/img/LIBRAS.svg' ); ?>" alt="" aria-hidden="true" focusable="false">
			</button>
			<section
				class="portal-libras-player__panel"
				id="portal-libras-player-panel"
				role="dialog"
				aria-modal="false"
				aria-labelledby="portal-libras-player-title"
				tabindex="-1"
				hidden
			>
				<header
					class="portal-libras-player__header"
					role="group"
					tabindex="0"
					aria-label="<?php esc_attr_e( 'Mover vídeo em LIBRAS: use as setas do teclado ou arraste', 'portal-video-libras' ); ?>"
				>
					<button
						class="portal-libras-player__resize"
						type="button"
						aria-label="<?php esc_attr_e( 'Redimensionar vídeo em LIBRAS: arraste ou use as setas esquerda e direita', 'portal-video-libras' ); ?>"
					></button>
					<h2 id="portal-libras-player-title">
						<?php esc_html_e( 'Vídeo em LIBRAS', 'portal-video-libras' ); ?>
					</h2>
					<button
						class="portal-libras-player__close"
						type="button"
						aria-label="<?php esc_attr_e( 'Fechar vídeo em LIBRAS', 'portal-video-libras' ); ?>"
					>
						<span aria-hidden="true">&times;</span>
					</button>
				</header>
				<div class="portal-libras-player__video">
					<?php
					// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Block and oEmbed output is generated by WordPress.
					echo $video;
					?>
				</div>
			</section>
		</div>
		<?php
	}

	/**
	 * Gets the current singular post's valid video URL.
	 *
	 * @return string
	 */
	private function get_video_url() {
		if ( ! is_singular() ) {
			return '';
		}

		$post_id = get_queried_object_id();

		if ( ! $post_id ) {
			return '';
		}

		$url = get_post_meta( $post_id, Post_Meta::META_KEY, true );

		return Post_Meta::is_valid_url( $url ) ? esc_url( $url, array( 'http', 'https' ) ) : '';
	}

	/**
	 * Builds native video/embed block markup, with an oEmbed fallback.
	 *
	 * @param string $url Valid video URL.
	 * @return string
	 */
	private function get_video_markup( $url ) {
		$path      = (string) wp_parse_url( $url, PHP_URL_PATH );
		$extension = strtolower( pathinfo( $path, PATHINFO_EXTENSION ) );

		if ( in_array( $extension, array( 'mp4', 'webm', 'ogv', 'm4v' ), true ) ) {
			$attributes = wp_json_encode( array( 'src' => $url ) );
			return do_blocks( '<!-- wp:video ' . $attributes . ' /-->' );
		}

		$provider = $this->get_provider_slug( $url );

		if ( $provider ) {
			add_filter( 'oembed_result', array( $this, 'enable_youtube_api' ), 10, 3 );
			$attributes = wp_json_encode(
				array(
					'url'             => $url,
					'type'            => 'video',
					'providerNameSlug' => $provider,
					'responsive'      => true,
				)
			);
			$markup = do_blocks( '<!-- wp:embed ' . $attributes . ' /-->' );

			if ( ! $markup ) {
				$markup = wp_oembed_get( $url );
			}
			remove_filter( 'oembed_result', array( $this, 'enable_youtube_api' ), 10 );

			return is_string( $markup ) ? $markup : '';
		}

		return wp_oembed_get( $url ) ?: '';
	}

	/**
	 * Enables the YouTube iframe API on WordPress-generated oEmbed markup.
	 *
	 * @param string $html   Embed HTML.
	 * @param string $url    Original video URL.
	 * @param array  $attr   Embed attributes.
	 * @return string
	 */
	public function enable_youtube_api( $html, $url, $attr ) {
		unset( $attr );

		if ( 'youtube' !== $this->get_provider_slug( $url ) ) {
			return $html;
		}

		return preg_replace_callback(
			'/(<iframe\b[^>]*\bsrc=["\'])([^"\']+)(["\'][^>]*>)/i',
			static function ( $matches ) {
				$src = html_entity_decode( $matches[2], ENT_QUOTES, get_bloginfo( 'charset' ) );
				$src = add_query_arg(
					array(
						'enablejsapi' => '1',
						'origin'      => home_url( '/' ),
					),
					$src
				);

				return $matches[1] . esc_url( $src, array( 'http', 'https' ) ) . $matches[3];
			},
			$html
		);
	}

	/**
	 * Returns a supported core/embed provider slug.
	 *
	 * @param string $url Video URL.
	 * @return string
	 */
	private function get_provider_slug( $url ) {
		$host = strtolower( (string) wp_parse_url( $url, PHP_URL_HOST ) );

		if ( in_array( $host, array( 'youtube.com', 'www.youtube.com', 'm.youtube.com', 'youtu.be', 'youtube-nocookie.com', 'www.youtube-nocookie.com' ), true ) ) {
			return 'youtube';
		}

		if ( in_array( $host, array( 'vimeo.com', 'www.vimeo.com', 'player.vimeo.com' ), true ) ) {
			return 'vimeo';
		}

		return '';
	}
}
